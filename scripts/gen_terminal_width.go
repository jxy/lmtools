//go:build ignore

// gen_terminal_width generates the editor's wide-character table from pinned
// Unicode data. Run it with go generate ./cmd/lmc; generation is offline.
package main

import (
	"bufio"
	"bytes"
	"crypto/sha256"
	"flag"
	"fmt"
	"go/format"
	"os"
	"strconv"
	"strings"
)

const sourceSHA256 = "a0cf29eacd00cfcaec4381c6b7c281685f18dbb4e7ff82b4076ccb342ca839aa"

type interval struct{ first, last uint32 }

func main() {
	input := flag.String("input", "", "Unicode 18.0.0 EastAsianWidth.txt")
	output := flag.String("output", "", "generated Go file")
	flag.Parse()
	if err := generate(*input, *output); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func generate(input, output string) error {
	data, err := os.ReadFile(input)
	if err != nil {
		return err
	}
	if got := fmt.Sprintf("%x", sha256.Sum256(data)); got != sourceSHA256 {
		return fmt.Errorf("Unicode data checksum: got %s, want %s", got, sourceSHA256)
	}
	var ranges []interval
	scanner := bufio.NewScanner(bytes.NewReader(data))
	for scanner.Scan() {
		line, _, _ := strings.Cut(scanner.Text(), "#")
		field, property, ok := strings.Cut(line, ";")
		if !ok || (strings.TrimSpace(property) != "W" && strings.TrimSpace(property) != "F") {
			continue
		}
		first, last, pair := strings.Cut(strings.TrimSpace(field), "..")
		if !pair {
			last = first
		}
		lo, err := strconv.ParseUint(first, 16, 32)
		if err != nil {
			return err
		}
		hi, err := strconv.ParseUint(last, 16, 32)
		if err != nil {
			return err
		}
		if lo > hi || hi > 0x10ffff || (len(ranges) > 0 && lo <= uint64(ranges[len(ranges)-1].last)) {
			return fmt.Errorf("invalid or unordered range: %s", field)
		}
		if len(ranges) > 0 && uint32(lo) == ranges[len(ranges)-1].last+1 {
			ranges[len(ranges)-1].last = uint32(hi)
		} else {
			ranges = append(ranges, interval{uint32(lo), uint32(hi)})
		}
	}
	if err := scanner.Err(); err != nil {
		return err
	}
	var b bytes.Buffer
	fmt.Fprintln(&b, "// Code generated by scripts/gen_terminal_width.go; DO NOT EDIT.")
	fmt.Fprintln(&b, "// Source: https://www.unicode.org/Public/18.0.0/ucd/EastAsianWidth.txt")
	fmt.Fprintf(&b, "// SHA-256: %s\n", sourceSHA256)
	fmt.Fprintln(&b, "// Unicode data copyright Unicode, Inc.; see testdata/unicode/LICENSE.txt.")
	fmt.Fprintln(&b, "package main\n\nimport \"unicode\"\n\nvar editWideRunes = &unicode.RangeTable{")
	fmt.Fprintln(&b, "R16: []unicode.Range16{")
	for _, r := range ranges {
		if r.first <= 0xffff {
			fmt.Fprintf(&b, "{Lo: %#x, Hi: %#x, Stride: 1},\n", r.first, min(r.last, 0xffff))
		}
	}
	fmt.Fprintln(&b, "},\nR32: []unicode.Range32{")
	for _, r := range ranges {
		if r.last > 0xffff {
			fmt.Fprintf(&b, "{Lo: %#x, Hi: %#x, Stride: 1},\n", max(r.first, 0x10000), r.last)
		}
	}
	fmt.Fprintln(&b, "},\n}")
	source, err := format.Source(b.Bytes())
	if err != nil {
		return err
	}
	return os.WriteFile(output, source, 0o644)
}
